#!/usr/bin/env node
// 从 global.d.ts 提取 hermesDesktop 里「可选(?:)」的顶层通道名，生成 TS 常量清单。
// 用法: node apps/desktop/scripts/gen-web-optional-channels.cjs
// 输出: apps/desktop/src/lib/bridge/web-optional-channels.ts
// 为什么: 上游把大量 Electron 专有通道声明为可选(?:)，消费方用 `?.()` / `if (!x)`
// 守卫。web-bridge 的 Proxy 兜底对缺失通道要返回 undefined（守卫短路），只有必需
// 通道才返回 unavailable() reject；但 Proxy 拿不到类型信息，靠这份生成清单判断。
const fs = require('fs')
const path = require('path')
const REPO = path.resolve(__dirname, '..', '..', '..')
const dts = path.join(REPO, 'apps/desktop/src/global.d.ts')
const out = path.join(REPO, 'apps/desktop/src/lib/bridge/web-optional-channels.ts')
const src = fs.readFileSync(dts, 'utf8')

// hermesDesktop 对象的所有顶层成员（6 空格缩进），key? 表示可选
const keys = []
const re = /^      ([a-zA-Z][a-zA-Z0-9]*)(\??):/gm
let m
while ((m = re.exec(src))) keys.push({ name: m[1], optional: m[2] === '?' })
const optional = keys.filter(k => k.optional).map(k => k.name).sort()

const header = `// GENERATED by scripts/gen-web-optional-channels.cjs — DO NOT EDIT BY HAND.
// Source of truth: apps/desktop/src/global.d.ts — the channels the desktop bridge
// declares OPTIONAL (?:). Consumers guard them with \`?.()\` optional-call or
// truthiness checks; when web has no implementation the bridge must hand these
// back as \`undefined\` so those guards short-circuit (a truthy stub would be
// called and reject into an unhandled promise -> pageerror).

export const WEB_OPTIONAL_CHANNELS = new Set<string>([
${optional.map(k => `  '${k}',`).join('\n')}
])
`
fs.writeFileSync(out, header)
console.log(`written ${out} (${optional.length} optional channels; total keys ${keys.length})`)
